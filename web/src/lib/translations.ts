export function translate(lang: Language, key: string, ...values: unknown[]): string {
  if (lang === 'en' && /^無法載入分類資料（\d+）$/.test(key)) return `Unable to load categories (${key.match(/\d+/)?.[0]}).`;
  const text = lang === 'en' ? EN[key] ?? key : key;
  return text.replace(/\{(\d+)\}/g, (_, index) => {
    if (Number(index) >= values.length) return `{${index}}`;
    const value = String(values[Number(index)] ?? '');
    return lang === 'en' ? EN[value] ?? value : value;
  });
}
export function sourceExcerpt(text?: string): string {
  if (!text) return '';
  if (text.length <= 360) return text;
  const end = text.lastIndexOf(' ', 360);
  return text.slice(0, end > 240 ? end : 360) + '…';
}
